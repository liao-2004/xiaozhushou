const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  scheduleShutdown: (p) => ipcRenderer.invoke('shutdown:schedule', p),
  cancelShutdown: () => ipcRenderer.invoke('shutdown:cancel'),
  scheduleWake: (p) => ipcRenderer.invoke('wake:schedule', p),
  cancelWake: () => ipcRenderer.invoke('wake:cancel'),
  shutdownNow: () => ipcRenderer.invoke('shutdown:now'),
  restartNow: () => ipcRenderer.invoke('restart:now'),
  abortShutdown: () => ipcRenderer.invoke('shutdown:abort'),
  hibernateNow: () => ipcRenderer.invoke('hibernate:now'),
  listTasks: () => ipcRenderer.invoke('tasks:list'),
  deleteTask: (n) => ipcRenderer.invoke('task:delete', n),
  scheduleCustom: (p) => ipcRenderer.invoke('custom:schedule', p),
  runCustomNow: (c) => ipcRenderer.invoke('custom:runNow', c),
  toggleTop: () => ipcRenderer.invoke('window:toggleTop'),
  minimize: () => ipcRenderer.invoke('window:minimize'),
  close: () => ipcRenderer.invoke('window:close'),
  captureShot: () => ipcRenderer.invoke('capture:shot'),
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: (c) => ipcRenderer.invoke('config:set', c),
  setTheme: (t) => ipcRenderer.invoke('theme:set', t),
  refreshShortcuts: () => ipcRenderer.invoke('shortcuts:refresh'),
  suspendShortcuts: () => ipcRenderer.invoke('shortcuts:suspend'),
  getAutostart: () => ipcRenderer.invoke('autostart:get'),
  setAutostart: (e) => ipcRenderer.invoke('autostart:set', e),
  downloadVideo: (p) => ipcRenderer.invoke('video:download', p),
  downloadOnline: (p) => ipcRenderer.invoke('video:downloadOnline', p),
  launchList: () => ipcRenderer.invoke('launch:list'),
  launchAdd: (item) => ipcRenderer.invoke('launch:add', item),
  launchRemove: (name) => ipcRenderer.invoke('launch:remove', name),
  launchRunAll: () => ipcRenderer.invoke('launch:runAll'),
  clipList: () => ipcRenderer.invoke('clip:list'),
  clipClear: () => ipcRenderer.invoke('clip:clear'),
  clipCopy: (t) => ipcRenderer.invoke('clip:copy', t),
  quickList: () => ipcRenderer.invoke('quick:list'),
  quickAdd: (t) => ipcRenderer.invoke('quick:add', t),
  quickDel: (i) => ipcRenderer.invoke('quick:del', i),
  notesList: () => ipcRenderer.invoke('notes:list'),
  notesAdd: (item) => ipcRenderer.invoke('notes:add', item),
  notesDel: (i) => ipcRenderer.invoke('notes:del', i),
  notesUpdate: (i, item) => ipcRenderer.invoke('notes:update', i, item),
  notesExport: () => ipcRenderer.invoke('notes:export'),
  notesPickImport: () => ipcRenderer.invoke('notes:pickImport'),
  notesAppend: (arr) => ipcRenderer.invoke('notes:append', arr),
  organizeRun: (mode) => ipcRenderer.invoke('organize:run', mode),
  onClipUpdate: (cb) => ipcRenderer.on('clip:update', (e, list) => cb(list)),
  onPinChanged: (cb) => ipcRenderer.on('pin:changed', (e, v) => cb(v)),
  onExitMini: (cb) => ipcRenderer.on('exit:mini', () => cb()),
  onAltOpen: (cb) => ipcRenderer.on('alt:open', () => cb())
});
